import json
import random
import re

import torch
from scipy.stats import beta
from transformers import AutoTokenizer, AutoModelForCausalLM

# ---------------------------------------------------------------
# Settings
# ---------------------------------------------------------------
model_names = [
    "Qwen/Qwen2.5-1.5B-Instruct",
    "HuggingFaceTB/SmolLM2-1.7B-Instruct",
]

n_samples = 300         # test with 5, then change to 300
max_new_tokens = 300
temperature = 0.7
prompt_seed = 1234
delta = 0.05

device = "cuda" if torch.cuda.is_available() else "cpu"
print("Device:", device)

# ---------------------------------------------------------------
# Distribution D
# ---------------------------------------------------------------
topics = [
    "the water cycle", "remote work", "coffee brewing", "black holes",
    "the Roman Empire", "recycling", "electric cars", "sleep",
    "the stock market", "volcanoes", "public libraries", "jazz music",
    "vaccines", "social media", "bicycles", "the printing press",
    "photosynthesis", "online privacy", "urban gardening", "earthquakes",
    "the Internet", "chess", "solar panels", "honeybees",
    "the French Revolution", "meditation", "airplanes", "inflation",
    "tea", "the Moon", "machine learning", "marathon running",
    "coral reefs", "renting vs buying a home", "the Silk Road", "bread baking",
    "thunderstorms", "video games", "time zones", "mountain hiking",
]

audiences = [
    "a high school student",
    "a busy manager",
    "a curious child",
    "a new employee",
    "a retiree",
    "a journalist",
]

constraint_types = ["bullets", "sentences", "forbidden_word", "word_range"]

count_values = [2, 3, 4, 5, 6]
forbidden_words = ["the", "and", "is", "of", "to"]
range_lows = [30, 40, 50, 60]


def sample_prompt(rng):
    topic = rng.choice(topics)
    audience = rng.choice(audiences)
    constraint_type = rng.choice(constraint_types)

    if constraint_type == "bullets":
        parameter = rng.choice(count_values)
        constraint_text = (
            "Use exactly " + str(parameter)
            + " bullet points, each starting with '-'."
        )
    elif constraint_type == "sentences":
        parameter = rng.choice(count_values)
        constraint_text = (
            "Write exactly " + str(parameter)
            + " sentences and no bullet points."
        )
    elif constraint_type == "forbidden_word":
        parameter = rng.choice(forbidden_words)
        constraint_text = (
            "Do not use the word '" + parameter + "' anywhere."
        )
    else:
        low = rng.choice(range_lows)
        high = low + 20
        parameter = (low, high)
        constraint_text = (
            "Use between " + str(low) + " and " + str(high) + " words."
        )

    prompt_text = (
        "Write a short text about " + topic
        + " for " + audience + ". " + constraint_text
    )
    return prompt_text, constraint_type, parameter


# ---------------------------------------------------------------
# Checker psi
# ---------------------------------------------------------------
def count_bullets(response):
    lines = response.split("\n")
    bullet_count = 0
    for line in lines:
        stripped_line = line.strip()
        if stripped_line.startswith("-"):
            bullet_count = bullet_count + 1
    return bullet_count


def count_sentences(response):
    pieces = re.split(r"[.!?]+(?:\s+|$)", response.strip())
    sentence_count = 0
    for piece in pieces:
        if piece.strip() != "":
            sentence_count = sentence_count + 1
    return sentence_count


def has_bullet_lines(response):
    lines = response.split("\n")
    for line in lines:
        if line.strip().startswith("-"):
            return True
    return False


def psi(constraint_type, parameter, response):
    text = response.strip()
    if text == "":
        return 0

    if constraint_type == "bullets":
        if count_bullets(text) == parameter:
            return 1
        return 0

    if constraint_type == "sentences":
        if has_bullet_lines(text):
            return 0
        if count_sentences(text) == parameter:
            return 1
        return 0

    if constraint_type == "forbidden_word":
        pattern = r"\b" + re.escape(parameter) + r"\b"
        if re.search(pattern, text, flags=re.IGNORECASE) is None:
            return 1
        return 0

    if constraint_type == "word_range":
        low = parameter[0]
        high = parameter[1]
        word_count = len(text.split())
        if word_count >= low and word_count <= high:
            return 1
        return 0

    return 0


# ---------------------------------------------------------------
# Clopper-Pearson interval
# ---------------------------------------------------------------
def clopper_pearson(k, n, delta):
    if k == 0:
        lower = 0.0
    else:
        lower = beta.ppf(delta / 2, k, n - k + 1)

    if k == n:
        upper = 1.0
    else:
        upper = beta.ppf(1 - delta / 2, k + 1, n - k)

    return lower, upper


# ---------------------------------------------------------------
# Generation
# ---------------------------------------------------------------
def generate_response(model, tokenizer, prompt_text, seed):
    messages = [{"role": "user", "content": prompt_text}]
    chat_text = tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    inputs = tokenizer(chat_text, return_tensors="pt").to(device)
    input_length = inputs["input_ids"].shape[1]

    torch.manual_seed(seed)
    with torch.no_grad():
        output_ids = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=True,
            temperature=temperature,
            top_p=1.0,
            pad_token_id=tokenizer.eos_token_id,
        )

    new_tokens = output_ids[0][input_length:]
    response = tokenizer.decode(new_tokens, skip_special_tokens=True)
    return response


# ---------------------------------------------------------------
# Draw prompts once so both models see the same prompts
# ---------------------------------------------------------------
prompt_rng = random.Random(prompt_seed)
samples = []
for i in range(n_samples):
    prompt_text, constraint_type, parameter = sample_prompt(prompt_rng)
    samples.append((prompt_text, constraint_type, parameter))

# ---------------------------------------------------------------
# Run each model
# ---------------------------------------------------------------
summary = {}

for model_name in model_names:
    print("")
    print("Loading", model_name)
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        torch_dtype=torch.float16 if device == "cuda" else torch.float32,
    ).to(device)
    model.eval()

    records = []
    success_count = 0

    for i in range(n_samples):
        prompt_text, constraint_type, parameter = samples[i]
        response = generate_response(model, tokenizer, prompt_text, seed=i)
        result = psi(constraint_type, parameter, response)
        success_count = success_count + result

        record = {
            "index": i,
            "prompt": prompt_text,
            "constraint_type": constraint_type,
            "parameter": parameter,
            "response": response,
            "psi": result,
        }
        records.append(record)

        if (i + 1) % 25 == 0:
            print("  done", i + 1, "of", n_samples)

    safe_name = model_name.replace("/", "_")
    output_path = "results_" + safe_name + ".json"
    with open(output_path, "w") as f:
        json.dump(records, f, indent=2)

    lower, upper = clopper_pearson(success_count, n_samples, delta)
    summary[model_name] = (success_count, lower, upper)

    print(model_name)
    print("  successes:", success_count, "out of", n_samples)
    print("  95% Clopper-Pearson interval: [", round(lower, 4), ",", round(upper, 4), "]")

    # Show up to 3 failures
    shown = 0
    for record in records:
        if record["psi"] == 0 and shown < 3:
            print("  FAILURE", record["index"], record["constraint_type"], record["parameter"])
            print("    prompt:", record["prompt"])
            print("    response:", record["response"][:300])
            shown = shown + 1

    del model
    del tokenizer
    if device == "cuda":
        torch.cuda.empty_cache()

print("")
print("SUMMARY")
for model_name in summary:
    k, lower, upper = summary[model_name]
    print(model_name, k, "/", n_samples, "[", round(lower, 4), ",", round(upper, 4), "]")

